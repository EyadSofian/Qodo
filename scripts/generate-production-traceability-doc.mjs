/**
 * Writes docs/ELEARNING_PRODUCTION_TRACEABILITY.md from the templates.
 *
 *   node scripts/generate-production-traceability-doc.mjs          # write it
 *   node scripts/generate-production-traceability-doc.mjs --check  # fail if it is stale
 *
 * The document is a view of shared/learningProduction/{workbookSource,
 * workflowTemplates,traceability}.js, never edited by hand: every row of the
 * "Content Development Checklists" workbook, visible or hidden, with the
 * template items that use it or the reason it is not used, followed by the
 * workbook anomalies and the decisions still open with the business owner.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { WORKBOOK_CHECKSUM, DETAIL_SHEETS, MASTER_ACTIVITIES } from '../shared/learningProduction/workbookSource.js';
import { ANOMALIES, OPEN_DECISIONS, ROW_CLASSIFICATIONS, traceRows } from '../shared/learningProduction/traceability.js';
import { SCENARIOS, SCENARIO_LABELS, TEMPLATE_OPTIONS, buildTemplate } from '../shared/learningProduction/workflowTemplates.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const TARGET = path.join(ROOT, 'docs', 'ELEARNING_PRODUCTION_TRACEABILITY.md');

const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const label = (value) => (value && typeof value === 'object' ? value.en : value);

function render() {
  const { detail, master } = traceRows();
  const lines = [];
  const out = (line = '') => lines.push(line);

  out('# E-Learning Production — workbook traceability');
  out();
  out('Generated by `scripts/generate-production-traceability-doc.mjs` — do not edit by hand.');
  out();
  out(`Source: *Content Development Checklists.xlsx*, SHA-256 \`${WORKBOOK_CHECKSUM}\`.`);
  out(`${DETAIL_SHEETS.length} detail sheets, ${detail.length} rows (${detail.filter((row) => row.hidden).length} hidden), and ${MASTER_ACTIVITIES.length} master-sheet cells.`);
  const untraced = [...detail, ...master].filter((row) => row.status === 'UNTRACED').length;
  out(untraced === 0 ? 'Every row is traced.' : `**${untraced} rows are untraced.**`);
  out();
  out('Statuses: **USED** — cited by at least one template item; **SHEET_FURNITURE** — a title, activity-ID or header row; ');
  out('**DUPLICATE** — a hidden copy of visible rows (see the note). Hidden rows are reference material: each one used by a template is');
  out('activated as a labelled proposal behind a template option, never as live status. `FALSE` checkbox cells are never read as status.');
  out();

  out('## Stages by scenario');
  out();
  for (const scenario of SCENARIOS) {
    const template = buildTemplate(scenario);
    out(`### ${label(SCENARIO_LABELS[scenario])}`);
    out();
    out('| # | Stage key | Stage | After | Origin | Tasks (required / all) |');
    out('| --- | --- | --- | --- | --- | --- |');
    template.stages.forEach((stage, index) => {
      const required = stage.tasks.filter((entry) => entry.classification === 'REQUIRED').length;
      out(`| ${index + 1} | \`${stage.key}\` | ${cell(label(stage.label))} | ${cell((stage.after ?? []).join(', ')) || '—'} | ${stage.origin ?? 'WORKBOOK'} | ${required} / ${stage.tasks.length} |`);
    });
    out();
  }
  out('Template options and their defaults:');
  out();
  for (const [key, option] of Object.entries(TEMPLATE_OPTIONS)) out(`- \`${key}\` — ${cell(label(option.label))} (default: ${option.default ? 'on' : 'off'})`);
  out();

  out('## Master sheet — Content Development Activities');
  out();
  out('| Cells | Text | Status | Used by |');
  out('| --- | --- | --- | --- |');
  for (const row of master) out(`| ${row.cells} | ${cell(row.text)} | ${row.status} | ${cell((row.usedBy ?? []).join(', ')) || '—'} |`);
  out();

  for (const sheet of DETAIL_SHEETS) {
    out(`## ${sheet.name}`);
    out();
    out('| Row | Hidden | Text | Status | Used by / note |');
    out('| --- | --- | --- | --- | --- |');
    for (const row of detail.filter((entry) => entry.sheet === sheet.name)) {
      const where = row.usedBy.length ? row.usedBy.join(', ') : row.note ?? '—';
      out(`| ${row.row} | ${row.hidden ? 'yes' : ''} | ${cell(row.text) || '—'} | ${row.status} | ${cell(where)} |`);
    }
    out();
  }

  out('## Row classifications');
  out();
  for (const entry of ROW_CLASSIFICATIONS) out(`- **${entry.sheet}** rows ${entry.rows.join(', ')} — ${entry.classification}: ${entry.note}`);
  out();

  out('## Workbook anomalies');
  out();
  out('| Where | Finding | Resolution |');
  out('| --- | --- | --- |');
  for (const entry of ANOMALIES) out(`| ${cell(entry.where)} | ${cell(entry.finding)} | ${cell(entry.resolution)} |`);
  out();

  out('## Open decisions for the business owner');
  out();
  out('Rows marked **release** should be settled before the module is merged and used for real work.');
  out();
  out('| | Question | What the system does until then |');
  out('| --- | --- | --- |');
  for (const entry of OPEN_DECISIONS) out(`| ${entry.affectsRelease ? '**release**' : ''} | ${cell(entry.question)} | ${cell(entry.default)} |`);
  out();
  return lines.join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (current !== text) {
    console.error(`${path.relative(ROOT, TARGET)} is stale — run node scripts/generate-production-traceability-doc.mjs`);
    process.exit(1);
  }
  console.log('Traceability document is current.');
} else {
  fs.writeFileSync(TARGET, text);
  console.log(`Wrote ${path.relative(ROOT, TARGET)}.`);
}
